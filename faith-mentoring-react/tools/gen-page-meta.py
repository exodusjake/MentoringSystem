#!/usr/bin/env python3
"""One-off generator: reads the original page HTML (../faith-mentoring-vite) and writes
src/app/pageMeta.js — per page: title, description, body class, and the ordered stylesheet list
(head <link>s and inline <style> blocks, which are saved as public/page-css/*.css)."""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT.parent / 'faith-mentoring-vite'
OUT_CSS = ROOT / 'public' / 'page-css'
OUT_CSS.mkdir(parents=True, exist_ok=True)

pages = {}
for f in sorted(SRC.glob('*/HTML/*.html')):
    key = f'{f.parent.parent.name}/{f.stem}'
    html = f.read_text(encoding='utf-8')
    head_end = html.index('</head>')
    title = re.search(r'<title>(.*?)</title>', html, re.S).group(1).strip()
    title = title.replace('&amp;', '&').replace('&ndash;', '–').replace('&mdash;', '—')
    desc = re.search(r'<meta name="description" content="([^"]*)"', html)
    body = re.search(r'<body([^>]*)>', html).group(1)
    body_class = (re.search(r'class="([^"]*)"', body) or [None, ''])[1]
    styles, n = [], 0
    for m in re.finditer(r'<link\b[^>]*rel="stylesheet"[^>]*>|<link\b[^>]*href="[^"]*"[^>]*rel="stylesheet"[^>]*>|<style\b[^>]*>([\s\S]*?)</style>', html):
        tag = m.group(0)
        where = 'head' if m.start() < head_end else 'body'
        if tag.startswith('<style'):
            n += 1
            name = f'{key.replace("/", "-")}-{n}.css'
            (OUT_CSS / name).write_text(m.group(1).strip('\n') + '\n', encoding='utf-8')
            styles.append({'href': f'/page-css/{name}', 'in': where})
        else:
            href = re.search(r'href="([^"]+)"', tag).group(1)
            styles.append({'href': href, 'in': where})
    entry = (SRC / 'src' / 'pages' / f.parent.parent.name / f'{f.stem}.js').read_text(encoding='utf-8')
    has = lambda mod: f'/shared/{mod}.js' in entry
    enh = {'select': has('ui-dropdown'), 'date': has('ui-datepicker'), 'time': has('ui-timepicker'),
           'modalMotion': has('modal-motion'), 'emptyStates': has('empty-states'),
           'portalChrome': has('sidebar-indicator'), 'smoothScroll': has('smooth-scroll'),
           'tooltips': has('apiClient')}
    pages[key] = {'title': title, 'description': desc.group(1) if desc else None, 'bodyClass': body_class,
                  'styles': styles, 'enhancers': {k: v for k, v in enh.items() if v}}

js = ('// Generated by tools/gen-page-meta.py from the original pages — do not edit by hand.\n'
      '// styles: in original cascade order; "in" marks whether the tag sat in <head> or <body>.\n'
      'export const PAGE_META = ' + json.dumps(pages, indent=2, ensure_ascii=False) + ';\n')
(ROOT / 'src' / 'app' / 'pageMeta.js').write_text(js, encoding='utf-8')
print(len(pages), 'pages;', sum(len(p['styles']) for p in pages.values()), 'style entries;',
      sum(1 for p in pages.values() for s in p['styles'] if s['in'] == 'body'), 'in body')
