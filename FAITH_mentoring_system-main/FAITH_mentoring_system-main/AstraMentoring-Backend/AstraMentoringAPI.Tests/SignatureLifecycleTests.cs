    [Fact]
    public async Task ReassigningSameMentorKeepsDateAndRepairRestoresOldDates()
    {
        using var db = new SqlConnection(connection);
        await db.ExecuteAsync("CREATE TABLE MentorMentee (AssignmentID int IDENTITY PRIMARY KEY, MentorID int, MenteeID int, AssignedDate date NOT NULL DEFAULT getdate(), IsActive bit)");
        var root = new DirectoryInfo(AppContext.BaseDirectory);
        while (root != null && !File.Exists(Path.Combine(root.FullName,"SQL","fix_assign_same_mentor_keeps_date.sql"))) root=root.Parent;
        var batches = System.Text.RegularExpressions.Regex.Split(
            await File.ReadAllTextAsync(Path.Combine(root!.FullName,"SQL","fix_assign_same_mentor_keeps_date.sql")), @"(?m)^GO\s*$");
        await db.ExecuteAsync(batches[0]);   // Part 1: sp_AssignMentor

        // Re-saving the same mentor keeps the original row and date.
        await db.ExecuteAsync("EXEC sp_AssignMentor 1, 100");
        await db.ExecuteAsync("UPDATE MentorMentee SET AssignedDate='2026-09-01'");
        await db.ExecuteAsync("EXEC sp_AssignMentor 1, 100");
        var rows = (await db.QueryAsync<(int Id, DateTime Date, bool Active)>("SELECT AssignmentID, AssignedDate, IsActive FROM MentorMentee WHERE MenteeID=1")).ToList();
        Assert.Single(rows);
        Assert.Equal(new DateTime(2026,9,1), rows[0].Date);
        // A real change of mentor still starts a new assignment.
        await db.ExecuteAsync("EXEC sp_AssignMentor 1, 200");
        Assert.Equal(200, await db.ExecuteScalarAsync<int>("SELECT MentorID FROM MentorMentee WHERE MenteeID=1 AND IsActive=1"));
        Assert.Equal(2, await db.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM MentorMentee WHERE MenteeID=1"));

        // Part 2 repair: only a same-mentor run gets its original date back.
        await db.ExecuteAsync("""
            INSERT MentorMentee (MentorID, MenteeID, AssignedDate, IsActive) VALUES
              (100, 5, '2026-09-01', 0), (100, 5, '2026-09-27', 1),
              (100, 6, '2026-09-01', 0), (200, 6, '2026-09-10', 0), (100, 6, '2026-09-27', 1),
              (100, 7, '2026-09-27', 1);
            """);
        var preview = batches[1];
        await db.ExecuteAsync(preview);  // @Apply = 0: must not change anything
        Assert.Equal(new DateTime(2026,9,27), await db.ExecuteScalarAsync<DateTime>("SELECT AssignedDate FROM MentorMentee WHERE MenteeID=5 AND IsActive=1"));
        await db.ExecuteAsync(preview.Replace("DECLARE @Apply BIT = 0;", "DECLARE @Apply BIT = 1;"));
        Assert.Equal(new DateTime(2026,9,1),  await db.ExecuteScalarAsync<DateTime>("SELECT AssignedDate FROM MentorMentee WHERE MenteeID=5 AND IsActive=1"));
        Assert.Equal(new DateTime(2026,9,27), await db.ExecuteScalarAsync<DateTime>("SELECT AssignedDate FROM MentorMentee WHERE MenteeID=6 AND IsActive=1"));
        Assert.Equal(new DateTime(2026,9,27), await db.ExecuteScalarAsync<DateTime>("SELECT AssignedDate FROM MentorMentee WHERE MenteeID=7 AND IsActive=1"));
    }

    [Fact]
    public async Task AttendanceCountsFollowLogsheetRules()
    {
        using var db = new SqlConnection(connection);
        await db.ExecuteAsync("""
            ALTER TABLE MenteeProfiles ADD SectionID int NULL, Section nvarchar(50) NULL, IsDropOut bit NULL;
            CREATE TABLE MentorMentee (AssignmentID int IDENTITY PRIMARY KEY, MentorID int, MenteeID int, AssignedDate date NOT NULL DEFAULT getdate(), IsActive bit);
            CREATE UNIQUE INDEX UQ_MentorMentee_Active ON MentorMentee (MentorID, MenteeID) WHERE IsActive = 1;
            CREATE TABLE Sections (SectionID int PRIMARY KEY, SectionCode nvarchar(50));
            CREATE TABLE Sessions (SessionID int PRIMARY KEY, MentorID int, Status nvarchar(20), SchoolYear nvarchar(20), Semester nvarchar(50),
                                   SessionDate datetime2, SectionCode nvarchar(50), SlotName nvarchar(50), RequestID int NULL);
            CREATE TABLE Attendance (AttendanceID int IDENTITY PRIMARY KEY, SessionID int, MenteeID int, IsPresent bit);
            CREATE TABLE SessionRequests (RequestID int PRIMARY KEY, MenteeID int, Status nvarchar(20));
            """);
        var root = new DirectoryInfo(AppContext.BaseDirectory);
        while (root != null && !File.Exists(Path.Combine(root.FullName,"SQL","fix_attendance_counting_rules.sql"))) root=root.Parent;
        var batches = System.Text.RegularExpressions.Regex.Split(
            await File.ReadAllTextAsync(Path.Combine(root!.FullName,"SQL","fix_attendance_counting_rules.sql")), @"(?m)^GO\s*$");
        await db.ExecuteAsync(batches[1]);   // fn_MenteeCheckpointAttendance
        await db.ExecuteAsync(batches[2]);   // sp_AssignMentor

        // Mentor 100 handles BSIT and BSN. Mentees: 1,2 BSIT; 3,4 BSN.
        await db.ExecuteAsync("""
            INSERT Sections VALUES (1,'BSIT'),(2,'BSN');
            INSERT MenteeProfiles (UserID, SectionID) VALUES (1,1),(2,1),(3,2),(4,2);
            INSERT MentorMentee (MentorID, MenteeID, AssignedDate, IsActive) VALUES
              (100,1,'2026-09-01',1),(100,2,'2026-09-01',1),(100,3,'2026-09-01',1);
            INSERT SessionRequests VALUES (50,3,'Approved');
            INSERT Sessions VALUES
              (10,100,'Completed','SY','Sem','2026-09-10','BSIT','Before Prelims',NULL),  -- BSIT regular
              (11,100,'Completed','SY','Sem','2026-09-10','BSN', 'Before Prelims',NULL),  -- BSN regular
              (12,100,'Completed','SY','Sem','2026-09-12',NULL,  'Before Prelims',50),    -- make-up booked by 3
              (13,100,'Completed','SY','Sem','2026-09-20','BSIT','After Prelims',NULL),   -- BSIT regular
              (14,100,'Cancelled','SY','Sem','2026-09-21','BSIT','Before Midterms',NULL), -- cancelled: ignored
              (15,100,'Completed','SY','Sem','2026-09-22','BSN', 'Mentoring Assembly',NULL);
            INSERT Attendance (SessionID, MenteeID, IsPresent) VALUES
              (10,1,1),(10,2,0),        -- 1 present, 2 absent (BSIT)
              (11,3,0),                 -- 3 missed own BSN session...
              (12,3,1),                 -- ...then attended the make-up he booked
              (12,2,1),                 -- 2 (BSIT) joined that make-up without booking
              (13,1,1),(13,1,1);
            """);

        async Task<(int Expected, int Attended)> Counts(int mentee) => await db.QuerySingleAsync<(int, int)>(
            "SELECT COUNT(*), ISNULL(SUM(Attended),0) FROM dbo.fn_MenteeCheckpointAttendance('SY','Sem') WHERE MentorID = 100 AND MenteeID = @m",
            new { m = mentee });

        Assert.Equal((2, 2), await Counts(1)); // own section only (BSIT: Before + After Prelims)
        Assert.Equal((2, 1), await Counts(2)); // missed BSIT Before Prelims, caught up at someone else's make-up
        Assert.Equal((2, 1), await Counts(3)); // BSN Before Prelims via booked make-up counts once; Assembly missed
        Assert.Equal((0, 0), await Counts(4)); // not assigned

        // Returning to a previous mentor keeps the first start date, so earlier attendance still counts.
        await db.ExecuteAsync("EXEC sp_AssignMentor 1, 200");
        await db.ExecuteAsync("EXEC sp_AssignMentor 1, 100");
        Assert.Equal(new DateTime(2026,9,1), await db.ExecuteScalarAsync<DateTime>("SELECT AssignedDate FROM MentorMentee WHERE MenteeID=1 AND IsActive=1"));
        Assert.Equal((2, 2), await Counts(1));
        // A first-time assignment still starts today.
        await db.ExecuteAsync("EXEC sp_AssignMentor 4, 100");
        Assert.Equal(DateTime.Today, await db.ExecuteScalarAsync<DateTime>("SELECT AssignedDate FROM MentorMentee WHERE MenteeID=4 AND IsActive=1"));
    }

