    private readonly string database = "AstraSignatureRegression_" + Guid.NewGuid().ToString("N");
    private readonly string folder = Path.Combine(Path.GetTempPath(), "AstraSignatureRegression_" + Guid.NewGuid().ToString("N"));
    private const string Master = "Server=(localdb)\\MSSQLLocalDB;Database=master;Trusted_Connection=True;TrustServerCertificate=True;Connect Timeout=10";
    private IConfiguration config = null!;
    private string connection = "";

    public async Task InitializeAsync()
    {
        using var master = new SqlConnection(Master);
        await master.ExecuteAsync($"CREATE DATABASE [{database}]");
        connection = new SqlConnectionStringBuilder(Master) { InitialCatalog=database }.ConnectionString;
        config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string,string?> {
            ["ConnectionStrings:DefaultConnection"]=connection,
            ["Jwt:Key"]="isolated-regression-test-key-not-used-in-production-123456789"
        }).Build();
        Directory.CreateDirectory(folder);
        using var db = new SqlConnection(connection);
        await db.ExecuteAsync("""
            CREATE TABLE Users (
                UserID int IDENTITY PRIMARY KEY, FirstName nvarchar(100), LastName nvarchar(100),
                Email nvarchar(200), PasswordHash nvarchar(200), ProfilePicture nvarchar(500),
                ContactNumber nvarchar(50), StudentNumber nvarchar(50), Role nvarchar(20),
                IsActive bit, CreatedAt datetime2, UpdatedAt datetime2, SchoolYear nvarchar(30),
                Semester nvarchar(30), Gender nvarchar(30), HasLoggedIn bit, EmailVerifiedAt datetime2 NULL, SignatureFilePath nvarchar(500));
            CREATE TABLE MentorProfiles (UserID int PRIMARY KEY, SignatureFilePath nvarchar(500));
            CREATE TABLE MenteeProfiles (UserID int PRIMARY KEY, SignatureFilePath nvarchar(500));
            """);
    }

    public async Task DisposeAsync()
    {
        SqlConnection.ClearAllPools();
        // Only the database generated by this fixture may ever be dropped.
        if (!System.Text.RegularExpressions.Regex.IsMatch(database, "^AstraSignatureRegression_[a-f0-9]{32}$"))
            throw new InvalidOperationException("Unexpected test database name.");
        using var master = new SqlConnection(Master);
        await master.ExecuteAsync($"IF DB_ID('{database}') IS NOT NULL BEGIN ALTER DATABASE [{database}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [{database}]; END");
        var root = Path.GetFullPath(Path.GetTempPath()).TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar;
        var target = Path.GetFullPath(folder);
        if (!target.StartsWith(root, StringComparison.OrdinalIgnoreCase) || !Path.GetFileName(target).StartsWith("AstraSignatureRegression_"))
            throw new InvalidOperationException("Unexpected upload directory.");
        if (Directory.Exists(target)) Directory.Delete(target, true);
    }

