    [Fact]
    public async Task HeadCannotPromoteItselfOrEditOtherAccounts()
    {
        var repo = new GenericRepository<User>(config);
        var auth = new AuthService(repo, null!, null!, null!, config);
        var head  = new User { FirstName="Head", LastName="User", Email="head@example.test", Role="Head",
            PasswordHash=auth.HashPassword("Pass-123456"), IsActive=true, HasLoggedIn=true };
        var admin = new User { FirstName="Main", LastName="Admin", Email="admin@example.test", Role="Admin",
            PasswordHash=auth.HashPassword("Admin-123456"), IsActive=true, HasLoggedIn=true };
        await repo.AddAsync(head); await repo.AddAsync(admin);
        var profiles = new UsersController(new ProfileService(repo,null!,null!,config));
        SetCaller(profiles,head);
        profiles.HttpContext.RequestServices = new ServiceCollection().AddSingleton(auth).BuildServiceProvider();

        Assert.IsType<OkObjectResult>(await profiles.Put(head.UserID,new UpdateUserRequest {
            FirstName="Head", LastName="User", Email=head.Email, Role="Admin", ContactNumber="09170000000" }));
        var savedHead = (await repo.GetByIdAsync(head.UserID))!;
        Assert.Equal(("Head","09170000000"),(savedHead.Role,savedHead.ContactNumber));

        Assert.IsType<ForbidResult>(await profiles.Put(admin.UserID,new UpdateUserRequest {
            FirstName="Main", LastName="Admin", Email=admin.Email, Role="Admin", NewPassword="Taken-over-1" }));
        Assert.NotNull(await auth.LoginAsync(new LoginRequest { Email=admin.Email, Password="Admin-123456" }));

        // Account creation and profile-row writes are Admin-only.
        static string? Roles(Type t, string method) => t.GetMethods().Where(m => m.Name == method)
            .SelectMany(m => m.GetCustomAttributes(typeof(Microsoft.AspNetCore.Authorization.AuthorizeAttribute), false))
            .Cast<Microsoft.AspNetCore.Authorization.AuthorizeAttribute>().Single().Roles;
        foreach (var m in new[] { "Register", "RegisterMentee", "RegisterMentor" })
            Assert.Equal("Admin", Roles(typeof(AuthController), m));
        foreach (var t in new[] { typeof(MentorProfilesController), typeof(MenteeProfilesController) })
            foreach (var m in new[] { "Post", "Put", "Delete" })
                Assert.Equal("Admin", Roles(t, m));
    }

