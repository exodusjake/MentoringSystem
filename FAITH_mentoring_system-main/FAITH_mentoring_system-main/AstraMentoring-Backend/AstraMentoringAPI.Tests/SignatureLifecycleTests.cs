    [InlineData("Admin")]
    [InlineData("Head")]
    [InlineData("Mentor")]
    [InlineData("Mentee")]
    public async Task SetupProfilePasswordAndReplacementPreserveSignature(string role)
    {
        var repo = new GenericRepository<User>(config);
        var auth = new AuthService(repo, null!, null!, null!, config);
        var user = new User { FirstName="Test", LastName=role, Email=role+"@example.test", Role=role,
            PasswordHash=auth.HashPassword("Original-password-123"), IsActive=true, HasLoggedIn=true };
        await repo.AddAsync(user);
        using var db = new SqlConnection(connection);
        var table = role == "Mentor" ? "MentorProfiles" : role == "Mentee" ? "MenteeProfiles" : "Users";
        if (table != "Users") await db.ExecuteAsync($"INSERT {table}(UserID) VALUES (@UserID)",user);
        var initial = await auth.LoginAsync(new LoginRequest { Email=user.Email, Password="Original-password-123" });
        Assert.True(JsonSerializer.SerializeToElement(initial!.User).GetProperty("setupRequired").GetBoolean());

        var signatures = new ESignatureController(config, new Environment(folder));
        SetCaller(signatures,user);
        var first = Assert.IsType<OkObjectResult>(await signatures.Upload(user.UserID,Png()));
        var path = JsonSerializer.SerializeToElement(first.Value).GetProperty("signatureFilePath").GetString()!;
        Assert.True(File.Exists(Path.Combine(folder,path.TrimStart('/'))));

        var profiles = new UsersController(new ProfileService(repo,null!,null!,config));
        SetCaller(profiles,user);
        profiles.HttpContext.RequestServices = new ServiceCollection().AddSingleton(auth).BuildServiceProvider();
        Assert.IsType<OkObjectResult>(await profiles.Put(user.UserID,new UpdateUserRequest {
            FirstName="Edited", LastName=role, Email=user.Email, Role=role, ContactNumber="09123456789" }));
        Assert.Equal(path,await db.ExecuteScalarAsync<string>($"SELECT SignatureFilePath FROM {table} WHERE UserID=@UserID",user));
        Assert.Equal("09123456789",(await repo.GetByIdAsync(user.UserID))!.ContactNumber);

        Assert.IsType<BadRequestObjectResult>(await profiles.Put(user.UserID,new UpdateUserRequest {
            FirstName="Edited", LastName=role, Email=user.Email, Role=role,
            CurrentPassword="incorrect", NewPassword="New-password-456" }));
        Assert.IsType<OkObjectResult>(await profiles.Put(user.UserID,new UpdateUserRequest {
            FirstName="Edited", LastName=role, Email=user.Email, Role=role,
            CurrentPassword="Original-password-123", NewPassword="New-password-456" }));
        Assert.Null(await auth.LoginAsync(new LoginRequest { Email=user.Email, Password="Original-password-123" }));
        var login = await auth.LoginAsync(new LoginRequest { Email=user.Email, Password="New-password-456" });
        Assert.NotNull(login);
        Assert.False(JsonSerializer.SerializeToElement(login.User).GetProperty("setupRequired").GetBoolean());
        Assert.Equal(path,await db.ExecuteScalarAsync<string>($"SELECT SignatureFilePath FROM {table} WHERE UserID=@UserID",user));

        // Simulate a failed save: old path and file must survive; new file is cleaned up.
        await db.ExecuteAsync($"CREATE TRIGGER RejectSignature ON {table} AFTER UPDATE AS BEGIN IF UPDATE(SignatureFilePath) THROW 51000, 'Injected test failure',1; END");
        var before = Directory.GetFiles(Path.Combine(folder,"uploads","signatures")).Length;
        await Assert.ThrowsAsync<SqlException>(()=>signatures.Upload(user.UserID,Png()));
        Assert.Equal(before,Directory.GetFiles(Path.Combine(folder,"uploads","signatures")).Length);
        Assert.True(File.Exists(Path.Combine(folder,path.TrimStart('/'))));
        Assert.Equal(path,await db.ExecuteScalarAsync<string>($"SELECT SignatureFilePath FROM {table} WHERE UserID=@UserID",user));
        await db.ExecuteAsync("DROP TRIGGER RejectSignature");
        var replacement = Assert.IsType<OkObjectResult>(await signatures.Upload(user.UserID,Png()));
        var newPath = JsonSerializer.SerializeToElement(replacement.Value).GetProperty("signatureFilePath").GetString()!;
        Assert.NotEqual(path,newPath);
        Assert.True(File.Exists(Path.Combine(folder,newPath.TrimStart('/'))));
        Assert.False(File.Exists(Path.Combine(folder,path.TrimStart('/'))));
    }

    [Fact]
    public async Task AssignmentAllowsMoreThanTwentyAndPreservesReassignment()
    {
        using var db = new SqlConnection(connection);
        await db.ExecuteAsync("CREATE TABLE MentorMentee (AssignmentID int IDENTITY PRIMARY KEY, MentorID int, MenteeID int, AssignedDate datetime2, IsActive bit)");
