    SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_NAME = 'MentorProfiles' AND COLUMN_NAME = 'SignatureFilePath'
)
    ALTER TABLE MentorProfiles ADD SignatureFilePath NVARCHAR(500) NULL;
GO

